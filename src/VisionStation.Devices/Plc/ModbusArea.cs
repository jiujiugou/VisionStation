namespace VisionStation.Devices.Plc;

/// <summary>
/// Modbus 四个标准功能区。
///
/// <para>
/// <b>定位</b>：地址模型的最底层词汇，被 <see cref="PlcAddress"/> 持有、
/// 由 <see cref="ModbusAddressParser"/> 按前缀产生、由两个驱动按功能区选功能码。
/// 本枚举不携带任何 IO 能力，纯数据。
/// </para>
/// <para>
/// <b>为什么功能区必须显式区分、不能只存一个数字偏移</b>：Modbus 的四个区是四张独立的表，
/// 同一个偏移 100 在 0x 是线圈、在 4x 是寄存器。把区域丢了，读回来的可能是完全另一个点位 ——
/// 这类错误不会报错，只会让产量数字对不上，是最难查的一类。
/// </para>
/// </summary>
public enum ModbusArea
{
    /// <summary>
    /// 线圈（0x），可读写。汇川 M/Y 变量映射到这里。
    /// 本项目的用途：写心跳/握手类开关量；触发与结果走的是保持寄存器（D 区）。
    /// </summary>
    Coil,

    /// <summary>
    /// 离散输入（1x），只读。汇川 X 物理输入映射到这里。
    /// 只读是协议规定，不是本项目的限制 —— 往这里写会被驱动直接拒绝（见 <c>WriteBit</c>）。
    /// </summary>
    DiscreteInput,

    /// <summary>
    /// 保持寄存器（4x），可读写。汇川 D 数据寄存器映射到这里。
    /// 本项目所有有业务含义的点位（D100 触发 / D101 结果 / D102 心跳）都在这个区。
    /// </summary>
    HoldingRegister,

    /// <summary>
    /// 输入寄存器（3x），只读。
    ///
    /// <para>
    /// <b>当前是一枚"有定义、无通路"的枚举值</b>：<see cref="ModbusAddressParser"/> 的两种写法都不产出它
    /// （<c>3x100</c> 会落到"不支持的寄存器区域"分支），两个驱动的 16 位读写又都只接受保持寄存器。
    /// 也就是说没有任何配置能让点位落进 3x。
    /// </para>
    /// <para>
    /// 保留它是因为 4 个区是协议事实，枚举写全比写 3 个少一层解释成本；
    /// 但要清楚：**它不是"即将支持"，而是"目前无法到达"**。真要用，得同时改解析器与两个驱动，
    /// 并在探针里补一条 3x 用例 —— 单改解析器只会得到"启动时能解析、轮询时永远读写失败"。
    /// </para>
    /// </summary>
    InputRegister,
}
