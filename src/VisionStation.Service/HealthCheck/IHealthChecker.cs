namespace VisionStation.Service;

/// <summary>
/// 健康检查接口 —— 开机自检。
///
/// <para>
/// <b>定位</b>：启动链路的第三环（连设备 → <b>自检</b> → 建库 → 起 VM 监听）。
/// 唯一调用方是 <c>AppHost.InitializeAsync</c>：它把返回的每一条逐项写日志，
/// 再把同一批结果交给界面汇总成状态栏一行（<c>HealthSummary.Describe</c>）。
/// 本接口不认识任何配置文件 —— 库路径、存储目录、配方、资源根都由组合根解析好传进来。
/// </para>
///
/// <para>
/// <b>归属</b>：DI 单例，但只在启动时被解析并调用一次。
/// 调用线程是 UI 线程（WPF 启动流程），所以实现里的磁盘探测必须短 ——
/// 理由不是性能，而是"启动线程停住了，看门狗那边就会判启动失败"。
/// </para>
///
/// <para>
/// <b>失败行为</b>：返回结果列表，**不抛异常**。单项检查自己出错也要变成该项的 FAIL 行 ——
/// 自检的结果是"提示"，不是"启动的门票"：最坏情况是操作员不知道哪里坏了，
/// 但程序照样起来、产线照样看得见状态。把失败升级成启动失败，等于用一个探针把程序拦死。
/// </para>
/// </summary>
public interface IHealthChecker
{
    /// <summary>
    /// 跑完全部检查项，一次性返回（顺序 = 设备、数据库、存储路径、检测引擎、配方）。
    ///
    /// 同步而不是异步：调用点只有启动那一处，且必须拿到结果才能继续；
    /// 每一项都是几十毫秒级的本地 IO，包成 Task 只会让"到底哪一项慢"更难定位。
    /// 内部逐项隔离异常，因此本方法对调用方而言没有失败返回值 —— 只有"哪几项没通过"。
    /// </summary>
    List<HealthResult> RunAll();
}
